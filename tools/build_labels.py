#!/usr/bin/env python3
"""Move every fixed page label, title and help text into presentation/presentationLabels/en-US.properties.

Workday translates an Extend page through translation keys (developer.workday.com "Translate Widgets Using the
Workday Extend Plugin for IntelliJ"): a .properties file per language in presentation/presentationLabels, bindings
"<% presentationLabels.<key> %>" on label, title and value, and the language in the SMD's languages[].

Run it after the page builders (CI does). It is idempotent: text that is already a binding is left alone, keys
still used anywhere are kept, keys no page uses any more are dropped. To add a language, add tools/translations/<language>-<COUNTRY>.json
({English text: translation}) and the code to the SMD; the .properties file is written from it.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRES = os.path.join(ROOT, 'app', 'presentation')
LABELS = os.path.join(PRES, 'presentationLabels')
DEFAULT = os.path.join(LABELS, 'en-US.properties')
BIND = re.compile(r'<%\s*presentationLabels\.([A-Za-z0-9_]+)\s*%>')


def key_part(s):
    return re.sub(r'[^A-Za-z0-9_]', '_', s)


def read_props(path):
    out = {}
    if not os.path.exists(path):
        return out
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or line.startswith('#') or '=' not in line:
                continue
            k, v = line.split('=', 1)
            out[k] = v.replace('\\n', '\n').replace('\\\\', '\\')
    return out


def write_props(path, props, header=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = header or ['# Default (English) text for every page label, title and help text. Keys: <Page>_<widget id>_<attribute>.',
                       '# Generated by tools/build_labels.py: edit the page builders, not this file.']
    for k in sorted(props):
        v = props[k].replace('\\', '\\\\').replace('\n', '\\n')
        lines.append(f'{k}={v}')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def localize(page_id, node, found, used, path):
    """Replace fixed text in place; record new keys in found and every key in used."""
    if isinstance(node, list):
        for i, n in enumerate(node):
            localize(page_id, n, found, used, path + [str(i)])
        return
    if not isinstance(node, dict):
        return
    name = node.get('id') or node.get('columnId') or '_'.join(path[-2:]) or 'node'
    attrs = ['label', 'title']
    if node.get('type') == 'richText':
        attrs.append('value')
    for a in attrs:
        v = node.get(a)
        if not isinstance(v, str) or not v.strip():
            continue
        m = BIND.fullmatch(v.strip())
        if m:
            used.add(m.group(1))
            continue
        if '<%' in v:
            continue  # a script: built from data, not translatable as a whole
        k = key_part(f'{page_id}_{name}_{a}')
        if k in found and found[k] != v:
            raise SystemExit(f'{page_id}: two different texts would share the key {k}; give the widgets ids')
        found[k] = v
        used.add(k)
        node[a] = f'<% presentationLabels.{k} %>'
    for key, child in node.items():
        if key in ('excel',):
            continue
        localize(page_id, child, found, used, path + [key])


# Card parameters that carry text a user reads (hero, tool pills, tiles, result cards). A plain single-quoted literal
# in such a parameter's value becomes presentationLabels.<key>, so cards follow the user's language like page labels.
# Literals compared with == / != (statuses), icons and colours are left alone.
TEXT_PARAMS = re.compile(r'^(heroTitle|heroLine|chipLabel|kpiLabel|kpiNote|tileTitle|tileLine|openLabel|toolsTitle|appLine|stepsTitle|stepsText|pill[A-Z]\w*)$')
ENTRY = re.compile(r"'(\w+)':\s*")
LIT = re.compile(r"(==\s*|!=\s*)?'((?:[^'\\]|\\.)*)'")


def localize_params(page_id, script, found, counter):
    """Rewrite the text literals in one card's parameters mapScript; returns the new script."""
    marks = list(ENTRY.finditer(script))
    out, pos = [], 0
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(script)
        out.append(script[pos:m.end()])
        value = script[m.end():end]
        if TEXT_PARAMS.match(m.group(1)):
            def sub(lm):
                text = lm.group(2)
                core = text.strip()
                if lm.group(1) or not re.search(r'[A-Za-z]', core) or core.startswith('wd-'):
                    return lm.group(0)
                k = None
                for kk, vv in found.items():
                    if vv == core and kk.startswith(page_id + '_card_'):
                        k = kk
                if k is None:
                    counter[0] += 1
                    k = key_part(f'{page_id}_card_{m.group(1)}_{counter[0]}')
                    found[k] = core
                lead = "' ' + " if text.startswith(' ') else ''
                trail = " + ' '" if text.endswith(' ') and core else ''
                return '(' + lead + 'presentationLabels.' + k + trail + ')'
            value = LIT.sub(sub, value)
        out.append(value)
        pos = end
    out.append(script[pos:]) if not marks else None
    return ''.join(out)


def localize_cards(page_id, node, found, counter):
    if isinstance(node, list):
        for n in node:
            localize_cards(page_id, n, found, counter)
    elif isinstance(node, dict):
        if node.get('type') == 'card' or 'cardId' in node:
            ps = node.get('parameters')
            if isinstance(ps, str) and '<%' in ps:
                node['parameters'] = localize_params(page_id, ps, found, counter)
        for v in node.values():
            localize_cards(page_id, v, found, counter)


def main():
    props = read_props(DEFAULT)
    used = set()
    for fn in sorted(os.listdir(PRES)):
        if not fn.endswith('.pmd'):
            continue
        p = os.path.join(PRES, fn)
        with open(p, encoding='utf-8') as f:
            raw = f.read()
        page = json.loads(raw)
        compact = raw.count('\n') <= 1  # pages written compact to fit the 100 KB limit stay compact (build_forms.py)
        found = {}
        if page.get('presentation', {}).get('body', {}).get('type') == 'hub':
            continue  # the hub's labels stay as written (tools/build_lab.py)
        localize(page['id'], page.get('presentation', {}), found, used, [])
        cards = {}
        localize_cards(page['id'], page.get('presentation', {}), cards, [0])
        found.update(cards)
        # Keys bound anywhere in the page (card parameters, scripts) count as used, so a second run keeps them.
        used.update(re.findall(r'presentationLabels\.([A-Za-z0-9_]+)', json.dumps(page, ensure_ascii=False)))
        clash = {k for k in found if k in props and props[k] != found[k]}
        props.update(found)
        if found:
            with open(p, 'w', encoding='utf-8') as f:
                f.write((json.dumps(page, ensure_ascii=False, separators=(',', ':')) if compact
                         else json.dumps(page, indent=2, ensure_ascii=False)) + '\n')
        print(f'{fn}: {len(found)} text(s) moved' + (f', {len(clash)} changed' if clash else ''))
    missing = sorted(used - set(props))
    if missing:
        raise SystemExit('bound keys with no text in en-US.properties: ' + ', '.join(missing))
    props = {k: v for k, v in props.items() if k in used}
    write_props(DEFAULT, props)
    size = os.path.getsize(DEFAULT)
    if size > 100 * 1024:
        raise SystemExit(f'en-US.properties is {size} bytes, over the 100 KB limit')
    print(f'wrote {os.path.relpath(DEFAULT, ROOT)}: {len(props)} keys, {size} bytes')
    write_translations(props)


def write_translations(props):
    """One <lang>.properties per tools/translations/<lang>.json ({English text: translation}). Keyed by the English
    text so translations survive key renames; text with no translation yet stays English and is listed, so every
    language file always has every key (the static check requires it)."""
    tdir = os.path.join(ROOT, 'tools', 'translations')
    if not os.path.isdir(tdir):
        return
    for fn in sorted(os.listdir(tdir)):
        if not fn.endswith('.json'):
            continue
        lang = fn[:-5]
        with open(os.path.join(tdir, fn), encoding='utf-8') as f:
            tr = json.load(f)
        out, todo = {}, []
        for k, v in props.items():
            out[k] = tr.get(v, v)
            if v not in tr:
                todo.append(k)
        path = os.path.join(LABELS, lang + '.properties')
        write_props(path, out, [f'# {lang} text for every page label, title and help text (keys as in en-US.properties).',
                                f'# Generated by tools/build_labels.py from tools/translations/{fn}: edit that file, not this one.'])
        unused = len([e for e in tr if e not in set(props.values())])
        print(f'wrote {os.path.relpath(path, ROOT)}: {len(out)} keys, {len(todo)} still in English'
              + (f' ({", ".join(todo[:8])}{"..." if len(todo) > 8 else ""})' if todo else '')
              + (f'; {unused} translation(s) no longer used' if unused else ''))


if __name__ == '__main__':
    main()
