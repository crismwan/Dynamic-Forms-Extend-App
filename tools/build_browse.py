"""Builds app/presentation/scripts/browse.script: folders for instance lists, so people can browse instead of guessing.

An instance list gets three attributes (see CLAUDE.md "Filtering instance lists"):
  "values":               browse.folderRoot(defs, rows)            the top folders
  "dynamicMonikerLevels": browse.folderLevel(defs, rows, self.promptSelections)
  "onSearch":             browse.folderFind(rows, event.query)     typing still searches every item

rows are plain maps {id, descriptor, search, <group keys>: [names]}; defs say which folders exist:
  kind 'group' (two levels: the groups with counts, then their items), 'flag' (items whose key is true) and 'az'.
A level with more than 40 items is split A to Z. Run: python3 tools/build_browse.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, 'app')
REF = json.load(open(os.path.join(APP, 'appManifest.json'), encoding='utf-8'))["referenceId"]

DS_WORDS = ["Worker", "Position", "Organization", "Job", "Location", "Compensation", "Absence", "Time", "Payroll",
            "Benefits", "Recruiting", "Learning", "Security", "Business Process", "Student", "Supplier", "Customer",
            "Journal", "Expense", "Project"]

SCRIPT = r'''/* Folders for instance lists (generated by tools/build_browse.py). */

var bOne = function(id, desc) {
  var m = {:};
  m.put('id', id);
  m.put('descriptor', desc);
  m;
};

var bDef = function(id, label, kind, key) {
  var m = {:};
  m.put('id', id);
  m.put('label', label);
  m.put('kind', kind);
  m.put('key', key);
  m;
};

var bItem = function(r) {
  bOne(r.id, r.descriptor);
};

var bVals = function(r, key) {
  var v = r[key];
  empty(v) ? ['(none)'] : v;
};

var bLetter = function(s) {
  var c = ('' + (s ?? '') + ' ').substring(0, 1).upperCase();
  validate:match('[A-Z]', c) ? c : '#';
};

var bCounts = function(keys, prefix) {
  var sorted = keys.sort();
  var out = [];
  var cur = '';
  var n = 0;
  var started = false;
  for (var g : sorted) {
    if (started && g == cur) {
      n = n + 1;
    } else {
      if (started) { out.add(bOne(prefix + cur, cur + '  (' + n + ')')); }
      cur = g;
      n = 1;
      started = true;
    }
  }
  if (started) { out.add(bOne(prefix + cur, cur + '  (' + n + ')')); }
  out;
};

var bGroups = function(rows, key) {
  var keys = [];
  for (var r : rows) {
    for (var v : bVals(r, key)) { keys.add(v); }
  }
  bCounts(keys, 'g:');
};

var bLetters = function(rows) {
  bCounts(rows.map(r => { bLetter(r.descriptor) }), 'l:');
};

var bIn = function(rows, key, g) {
  rows.filter(r => { bVals(r, key).contains(g) });
};

var bPick = function(items, sel, at, max) {
  sel.size() > at ? [items.filter(r => { ('l:' + bLetter(r.descriptor)) == sel[at] }).map(r => { bItem(r) }), false] :
    (items.size() > max ? [bLetters(items), true] : [items.map(r => { bItem(r) }), false]);
};

var folderRoot = function(defs, rows) {
  defs.map(d => { bOne(d.id, d.label + (d.kind == 'flag' ? '  (' + rows.filter(r => { r[d.key] == true }).size() + ')' : '')) });
};

var folderLevel = function(defs, rows, sel) {
  var s = sel ?? [];
  var top = s.size() > 0 ? s[0] : '';
  var hit = defs.filter(d => { d.id == top });
  var d = hit.size() > 0 ? hit.get(0) : bDef('', '', 'none', '');
  d.kind == 'flag' ? bPick(rows.filter(r => { r[d.key] == true }), s, 1, 40) :
    (d.kind == 'az' ? bPick(rows, s, 1, 0) :
      (d.kind == 'group' ? (s.size() < 2 ? [bGroups(rows, d.key), true] : bPick(bIn(rows, d.key, s[1].substringAfter('g:')), s, 2, 40)) :
        (d.kind == 'filled' ? (s.size() < 2 ? [bGroups(rows.filter(r => { !empty(r[d.key]) }), d.key), true] : bPick(bIn(rows, d.key, s[1].substringAfter('g:')), s, 2, 40)) : [[], false])));
};

var folderFind = function(rows, q) {
  var t = ('' + (q ?? '')).lowerCase().trim();
  var w = empty(t) ? [] : t.split(' ').filter(x => { !empty(x) });
  empty(w) ? [] : rows.filter(r => { w.filter(x => { !r.search.contains(x) }).size() == 0 }).map(r => { bItem(r) });
};

var dName = function(o) {
  empty(o) ? [] : ['' + (o.descriptor ?? '')];
};

var dNames = function(list) {
  empty(list) ? [] : list.map(o => { '' + (o.descriptor ?? '') });
};

var bRow = function(id, desc, more) {
  var m = {:};
  m.put('id', id);
  m.put('descriptor', desc);
  m.put('search', (desc + ' ' + more).lowerCase());
  m;
};

var posName = function(x) {
  (x.positionID ?? '') + ' ' + (x.positionTitle ?? '') + (empty(x.worker) ? ' (Unfilled)' : ' - ' + (x.worker.descriptor ?? ''));
};

var posRow = function(x) {
  var org = dName(x.supervisoryOrganization);
  var mgr = dName(x.manager);
  var loc = dName(x.location);
  var m = bRow(x.workdayID, posName(x), org.join(' ') + ' ' + mgr.join(' ') + ' ' + loc.join(' '));
  m.put('org', org);
  m.put('mgr', mgr);
  m.put('loc', loc);
  m.put('open', empty(x.worker));
  m;
};

var posRows = function(rows) {
  (rows ?? []).map(x => { posRow(x) });
};

var orgRow = function(x) {
  var mgr = dName(x.supervisoryManager);
  var sup = dName(x.superiorOrganization);
  var loc = dName(x.primaryLocation);
  var m = bRow(x.workdayID, '' + (x.name ?? ''), mgr.join(' ') + ' ' + sup.join(' ') + ' ' + loc.join(' '));
  m.put('mgr', mgr);
  m.put('sup', sup);
  m.put('loc', loc);
  m;
};

var workerRow = function(x) {
  var org = dName(x.supervisoryOrganization);
  var mgr = dNames(x.workersManager);
  var loc = dName(x.location);
  var m = bRow(x.worker.id, '' + (x.worker.descriptor ?? ''), org.join(' ') + ' ' + mgr.join(' ') + ' ' + loc.join(' '));
  m.put('org', org);
  m.put('mgr', mgr);
  m.put('loc', loc);
  m;
};

var domainRow = function(x) {
  var area = dNames(x.functionalAreas);
  var m = bRow(x.workdayID, '' + (x.domainName ?? ''), '');
  m.put('area', area);
  m;
};

var rowsFor = function(key, orgs, positions, domains, workers) {
  key == 'positions' ? posRows(positions) :
    (key == 'orgs' ? (orgs ?? []).map(x => { orgRow(x) }) :
      (key == 'workers' ? (workers ?? []).filter(x => { !empty(x.worker) }).map(x => { workerRow(x) }) :
        (key == 'domains' ? (domains ?? []).map(x => { domainRow(x) }) : [])));
};

var defsFor = function(key) {
  key == 'positions' ? [bDef('byOrg', 'By organization', 'group', 'org'), bDef('byManager', 'By manager', 'group', 'mgr'),
                        bDef('byLocation', 'By location', 'group', 'loc'), bDef('unfilled', 'Unfilled positions', 'flag', 'open'),
                        bDef('az', 'A to Z', 'az', '')] :
    (key == 'orgs' ? [bDef('byManager', 'By manager', 'group', 'mgr'), bDef('bySuperior', 'By superior organization', 'group', 'sup'),
                      bDef('byLocation', 'By location', 'group', 'loc'), bDef('az', 'A to Z', 'az', '')] :
      (key == 'workers' ? [bDef('byOrg', 'By organization', 'group', 'org'), bDef('byManager', 'By manager', 'group', 'mgr'),
                           bDef('byLocation', 'By location', 'group', 'loc'), bDef('az', 'A to Z', 'az', '')] :
        (key == 'domains' ? [bDef('byArea', 'By functional area', 'group', 'area'), bDef('az', 'A to Z', 'az', '')] : [])));
};

var domItem = function(x) {
  var m = {:};
  m.put('id', x.workdayID);
  m.put('descriptor', '' + x.domainName);
  m;
};

var domHas = function(x, g) {
  empty(x.functionalAreas) ? g == '(none)' : x.functionalAreas.filter(a => { ('' + a.descriptor) == g }).size() > 0;
};

var domAreas = function(raw) {
  var keys = [];
  for (var x : raw) {
    if (empty(x.functionalAreas)) { keys.add('(none)'); } else { for (var a : x.functionalAreas) { keys.add('' + a.descriptor); } }
  }
  bCounts(keys, 'g:');
};

var domLevel = function(raw, sel) {
  var s = sel ?? [];
  var top = s.size() > 0 ? s[0] : '';
  var n = s.size();
  top == 'az' ? (n < 2 ? [bCounts(raw.map(x => { bLetter(x.domainName) }), 'l:'), true] :
      [raw.filter(x => { ('l:' + bLetter(x.domainName)) == s[1] }).map(x => { bOne(x.workdayID, '' + x.domainName) }), false]) :
    (n < 2 ? [domAreas(raw), true] :
      bPick(raw.filter(x => { domHas(x, s[1].substringAfter('g:')) }).map(x => { domItem(x) }), s, 2, 40));
};

var domFind = function(raw, q) {
  var t = ('' + (q ?? '')).lowerCase().trim();
  empty(t) ? [] : raw.filter(x => { ('' + x.domainName).lowerCase().contains(t) }).map(x => { bOne(x.workdayID, '' + x.domainName) });
};

var levelFor = function(key, orgs, positions, domains, workers, sel) {
  key == 'domains' ? domLevel(domains ?? [], sel) : folderLevel(defsFor(key), rowsFor(key, orgs, positions, domains, workers), sel);
};

var findFor = function(key, orgs, positions, domains, workers, q) {
  key == 'domains' ? domFind(domains ?? [], q) : folderFind(rowsFor(key, orgs, positions, domains, workers), q);
};

var rootFor = function(key, positions) {
  folderRoot(defsFor(key), key == 'positions' ? posRows(positions) : []);
};

var dsQuery = function(q, appOnly) {
  var s = ('' + (q ?? '')).replace('\'', '').replace('\\', '').trim();
  (appOnly == true) ? '{REF} ' + s : s;
};

var dsItems = function(res, useId) {
  (res ?? []).map(x => { bOne(useId ? x.id : x.alias, (x.alias ?? '') + ' · ' + (empty(x.primaryBusinessObject) ? '' : (x.primaryBusinessObject.descriptor ?? ''))) });
};

var dsRoot = function() {
  [bOne('app', 'This app\'s data sources'), bOne('byObject', 'By business object')];
};

var dsLevelQuery = function(sel) {
  var s = sel ?? [];
  s.size() > 1 ? s[1].substringAfter('w:') : ((s.size() > 0 && s[0] == 'app') ? '{REF}' : '{REF}');
};

var dsNoCall = function(sel) {
  var s = sel ?? [];
  s.size() == 1 && s[0] == 'byObject';
};

var dsLevel = function(sel, res, useId) {
  var s = sel ?? [];
  (s.size() == 1 && s[0] == 'byObject') ? [{DS_WORDS}.map(w => { bOne('w:' + w, w) }), true] : [dsItems(res, useId), false];
};

var fieldPack = function(list) {
  (list ?? []).map(f => { (f.alias ?? '') + '|' + (f.type ?? '') + '|' + (empty(f.relatedBusinessObject) ? '' : (f.relatedBusinessObject.descriptor ?? '')) }).join('\n');
};

var fieldRow = function(line) {
  var p = line.splitByRegex('[|]');
  var alias = p.size() > 0 ? p[0] : '';
  var ty = p.size() > 1 ? p[1] : '';
  var rel = p.size() > 2 ? p[2] : '';
  var m = bRow(alias, alias + ' · ' + ty + (empty(rel) ? '' : ' of ' + rel), '');
  m.put('ty', [ty]);
  m.put('rel', empty(rel) ? [] : [rel]);
  m;
};

var fieldRows = function(packed) {
  empty(packed) ? [] : ('' + packed).splitByRegex('\n').filter(l => { !empty(l) }).map(l => { fieldRow(l) });
};

var typeCode = function(t) {
  ('' + (t ?? '')).lowerCase().substringBefore(' ').substringBefore('-') + 'Type';
};

var fieldFilter = function(rows, types, rel) {
  var r = ('' + (rel ?? '')).lowerCase().trim();
  rows.filter(x => { (empty(types) || types.contains(typeCode(x.ty[0]))) && (empty(r) || x.search.contains(r)) });
};

var fieldDefs = function() {
  [bDef('byType', 'By type', 'group', 'ty'), bDef('byRel', 'Instance fields, by related object', 'filled', 'rel'), bDef('az', 'A to Z', 'az', '')];
};

var nameRow = function(x, idKey, nameKey, groupKey) {
  var g = empty(groupKey) ? [] : (empty(x[groupKey]) ? [] : ['' + x[groupKey]]);
  var m = bRow('' + x[idKey], '' + (x[nameKey] ?? x[idKey]), g.join(' '));
  m.put('grp', g);
  m;
};

var nameRows = function(list, idKey, nameKey, groupKey) {
  (list ?? []).map(x => { nameRow(x, idKey, nameKey, groupKey) });
};

var nameDefs = function(groupLabel) {
  empty(groupLabel) ? [bDef('az', 'A to Z', 'az', '')] : [bDef('byGroup', groupLabel, 'group', 'grp'), bDef('az', 'A to Z', 'az', '')];
};

{
  "bOne": bOne, "bDef": bDef, "bItem": bItem, "bVals": bVals, "bLetter": bLetter, "bCounts": bCounts, "bGroups": bGroups,
  "bLetters": bLetters, "bIn": bIn, "bPick": bPick, "folderRoot": folderRoot, "folderLevel": folderLevel, "folderFind": folderFind,
  "dName": dName, "dNames": dNames, "bRow": bRow, "posName": posName, "posRows": posRows, "posRow": posRow, "orgRow": orgRow,
  "workerRow": workerRow, "domainRow": domainRow, "rowsFor": rowsFor, "defsFor": defsFor, "domItem": domItem, "domHas": domHas, "domAreas": domAreas, "domLevel": domLevel, "domFind": domFind, "levelFor": levelFor, "findFor": findFor, "rootFor": rootFor, "dsQuery": dsQuery, "dsItems": dsItems,
  "dsRoot": dsRoot, "dsLevelQuery": dsLevelQuery, "dsNoCall": dsNoCall, "dsLevel": dsLevel, "fieldPack": fieldPack, "fieldRow": fieldRow,
  "fieldRows": fieldRows, "typeCode": typeCode, "fieldFilter": fieldFilter, "fieldDefs": fieldDefs, "nameRows": nameRows,
  "nameRow": nameRow, "nameDefs": nameDefs
}
'''

out = SCRIPT.replace('{REF}', REF).replace('{DS_WORDS}', '[' + ', '.join("'%s'" % w for w in DS_WORDS) + ']')
with open(os.path.join(APP, 'presentation', 'scripts', 'browse.script'), 'w', encoding='utf-8') as f:
    f.write(out)
print('browse.script: %d bytes' % len(out))
